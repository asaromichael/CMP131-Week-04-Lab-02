num1 = float(input("Enter the first number."))
num2 = float(input("Enter the second number, this must not be a zero."))

addition = num1 + num2
print("The numbers added is ", addition)

subtraction = num1 - num2
print("The second number subtracted from the first is ", subtraction)

multiplication = num1 * num2
print("The numbers multiplied is ", multiplication)

division = num1 / num2
print("The first number divided by the second is ", division)

power = num1 ** num2
print("The first number raised to the second number is ", power)

average = (num1 + num2) / 2
print("The average of the two numbers is ", average)